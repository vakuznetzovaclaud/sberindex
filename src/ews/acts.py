OTHER = "иное/не указана"            # причина не установлена ни по тексту, ни по названию
SCHEMA = {"type": "object", "properties": {
    "режим": {"type": "string", "enum": ["чрезвычайная ситуация", "повышенная готовность", "иное"]},
    "уровень": {"type": "string", "enum": ["локальный", "муниципальный", "межмуниципальный", "региональный", "межрегиональный", "федеральный", "не указан"]},
    "причина_дословно": {"type": "string"},
    "дата_начала": {"type": "string"},
    "дата_окончания": {"type": "string"},
    "вся_территория_субъекта": {"type": "boolean"},
    "муниципальные_образования": {"type": "array", "items": {"type": "string"}},
    "населённые_пункты": {"type": "array", "items": {"type": "string"}},
    "число_пострадавших_домов": {"type": "integer"},
    "число_пострадавших_людей": {"type": "integer"}},
    "required": ["режим", "уровень", "причина_дословно", "дата_начала", "дата_окончания", "вся_территория_субъекта",
                 "муниципальные_образования", "населённые_пункты", "число_пострадавших_домов", "число_пострадавших_людей"]}
PROMPT = """Ниже текст официального правового акта субъекта РФ (распознан OCR, возможны опечатки).
Выпиши из него факты строго по тексту, не используя свои знания о событиях:
- режим и его уровень;
- причину дословно — фразу из акта, объясняющую, что произошло (например «в результате прохождения весеннего паводка»);
- дату начала и окончания режима в формате ГГГГ-ММ-ДД (если нет — пустая строка);
- территорию: весь субъект или перечень муниципальных образований и населённых пунктов, как они названы в акте;
- число пострадавших домов и людей, если оно названо (иначе 0).

ТЕКСТ АКТА:
{text}"""


def fetch_list(date_from=None, date_to=None):
    c = config()
    date_from, date_to = date_from or c["acts"]["period_from"], date_to or c["acts"]["period_to"]
    docs = {}
    for q in c["acts"]["queries"]:
        page, pages = 1, 1
        while page <= pages:
            d = json.loads(get(c["sources"]["acts_api"], {"Name": q, "PublishDateFrom": date_from, "PublishDateTo": date_to, "PageSize": 200, "Index": page}))
            pages = d.get("pagesTotalCount") or 1
            for x in d["items"]:
                docs[x["eoNumber"]] = x
            page += 1
            time.sleep(1)
    rows = []
    for x in docs.values():
        name = (x["name"] or "").lower().replace("\n", " ")
        rows.append({"eo": x["eoNumber"], "region_code": int(x["eoNumber"][:2]), "doc_date": x["documentDate"][:10],
                     "pub_date": x["publishDateShort"][:10], "title": (x["complexName"] or "").replace("\n", " "),
                     "action": next((a for a, p in ACTION if re.search(p, name)), "иное"),
                     "regime_title": "ЧС" if "чрезвычайн" in name else ("повышенная готовность" if "повышенной готовности" in name else "иное")})
    df = pd.DataFrame(rows).sort_values("pub_date")
    DIR.mkdir(parents=True, exist_ok=True)
    df.to_parquet(DIR / f"acts_{date_from[-4:]}_{date_to[-4:]}.parquet")
    return df


def pdf_of(eo):
    """PDF акта (кэшируется). Портал ограничивает параллельные загрузки — качать последовательно с паузой."""
    pdf = DIR / "pdf" / f"{eo}.pdf"
    pdf.parent.mkdir(parents=True, exist_ok=True)
    if not pdf.exists():
        data = get(config()["sources"]["acts_pdf"].format(eo=eo), timeout=40, tries=2, binary=True)
        if data[:4] != b"%PDF":
            raise RuntimeError(f"PDF не получен: {eo}")
        pdf.write_bytes(data)
        time.sleep(config()["crawl"]["pause_s"])
    return pdf


def text_of(eo):
    """OCR-текст акта (кэшируется)."""
    out = DIR / "ocr" / f"{eo}.txt"
    if out.exists():
        return out.read_text()
    out.parent.mkdir(parents=True, exist_ok=True)
    txt = ocr.pdf_to_text(pdf_of(eo))
    out.write_text(txt)
    return txt


def cause_category(text):
    return next((c for c, p in CAUSES.items() if re.search(p, text or "", re.I)), OTHER)


def extract(eo):
    """Факты акта по JSON-схеме + категория причины по правилам на дословной причине."""
    res = llm.ask(PROMPT.format(text=text_of(eo)[:12000]), SCHEMA)
    res["категория_причины"] = cause_category(res.get("причина_дословно", ""))
    return res


def extracted_path():
    INTERIM.mkdir(parents=True, exist_ok=True)
    return INTERIM / "acts_extracted.jsonl"
