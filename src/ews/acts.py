"""Реестр актов субъектов РФ о режимах ЧС и повышенной готовности с портала официального опубликования правовых актов
(publication.pravo.gov.ru): список актов, PDF, распознавание (OCR), извлечение фактов моделью и категория причины
по правилам.
Дата знания события — дата официальной публикации акта."""
import json
import re
import time

import pandas as pd

from . import llm, ocr
from .paths import RAW, INTERIM, config
