"""Правила извлечения масштаба и отбора постов официальных каналов на ручных примерах."""
from ews import news_official as no


def test_scale_groups():
    s = no.scale("Подтоплены 120 жилых домов и 35 приусадебных участков, эвакуировано 45 человек.")
    assert s == {"дома": 120, "эвакуированы": 45, "без света и тепла": 0}


def test_scale_thousands_and_years():
    s = no.scale("По состоянию на 22 апреля 2024 года остаются подтопленными более 12 300 жилых домов; без электроснабжения 1 500 человек.")
    assert s["дома"] == 12300 and s["без света и тепла"] == 1500


def test_scale_empty():
    assert sum(no.scale("Сотрудники МЧС провели учения на водоёме.").values()) == 0
